public class Calculo_media {
    /**
     * @param args
     * @throws Exception
     */
    public static void main(String[] args) throws Exception {
       int a =5;
        System.out.println("a");
        a+=1;
        System.out.println("Após o incremento, o valor de a é: " + a);
        a-=3;
        System.out.println("Após o decremento, o valor de a é: " + a);
        a*=2;
        System.out.println("Após a multiplicação, o valor de a é: " + a);
        a/=4;
        System.out.println("Após a divisão, o valor de a é: " + a); 
        a%=3;
        System.out.println("Após o módulo, o valor de a é: " + a);
            
        
    }
}
